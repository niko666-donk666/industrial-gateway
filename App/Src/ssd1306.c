static const uint8_t *GlyphFor(char c)
{
    for (uint32_t i = 0; i < (sizeof(s_glyphs) / sizeof(s_glyphs[0])); ++i) {
        if (s_glyphs[i].c == c) return s_glyphs[i].col;
    }
    return s_glyphs[0].col;
}

static bool WriteCommand(uint8_t command)
{
    uint8_t packet[2] = {0x00U, command};
    return HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, packet, sizeof(packet), 20U) == HAL_OK;
}

bool SSD1306_Init(void)
{
    static const uint8_t init_commands[] = {
        0xAE, 0x20, 0x00, 0x40, 0xA1, 0xC8, 0x81, 0x7F, 0xA6,
        0xA8, 0x3F, 0xD3, 0x00, 0xDA, 0x12, 0xD5, 0x80, 0xD9,
        0xF1, 0xDB, 0x40, 0x8D, 0x14, 0xAF
    };

    s_ready = false;
    if (HAL_I2C_IsDeviceReady(&hi2c1, SSD1306_I2C_ADDR, 3U, 100U) != HAL_OK) return false;
    for (uint32_t i = 0; i < sizeof(init_commands); ++i) {
        if (!WriteCommand(init_commands[i])) return false;
    }
    SSD1306_Clear();
    s_ready = true;
    SSD1306_Update();
    return true;
}

bool SSD1306_IsReady(void) { return s_ready; }

void SSD1306_Clear(void) { memset(s_buffer, 0, sizeof(s_buffer)); }

void SSD1306_WriteString(uint8_t row, const char *text)
{
    if (row >= SSD1306_PAGES || text == NULL) return;
    uint16_t column = 0U;
    while (*text != '\0' && column <= (SSD1306_WIDTH - 6U)) {
        const uint8_t *glyph = GlyphFor(*text++);
        for (uint8_t i = 0; i < 5U; ++i) s_buffer[(row * SSD1306_WIDTH) + column + i] = glyph[i];
        s_buffer[(row * SSD1306_WIDTH) + column + 5U] = 0x00U;
        column += 6U;
    }
}

void SSD1306_Update(void)
{
    if (!s_ready) return;
    for (uint8_t page = 0; page < SSD1306_PAGES; ++page) {
        if (!WriteCommand((uint8_t)(0xB0U + page)) || !WriteCommand(0x00U) || !WriteCommand(0x10U)) return;
        uint8_t packet[SSD1306_WIDTH + 1U];
        packet[0] = 0x40U;
        memcpy(&packet[1], &s_buffer[page * SSD1306_WIDTH], SSD1306_WIDTH);
        if (HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, packet, sizeof(packet), 100U) != HAL_OK) return;
    }
}
